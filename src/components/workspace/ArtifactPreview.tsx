'use client';

import React, { useState } from 'react';
import { useChat } from '@/context/ChatContext';
import { Code, Table as TableIcon, Copy, Check, Terminal, Download, FileSpreadsheet } from 'lucide-react';

export const ArtifactPreview: React.FC = () => {
  const { currentConversation } = useChat();
  const [copiedId, setCopiedId] = useState<string | null>(null);

  const codeArtifacts =
    currentConversation?.messages.flatMap((m) => m.interactiveElements?.codeBlocks || []) || [];

  const tableArtifacts =
    currentConversation?.messages.flatMap((m) => m.interactiveElements?.tables || []) || [];

  const handleCopy = (code: string, id: string) => {
    navigator.clipboard.writeText(code);
    setCopiedId(id);
    setTimeout(() => setCopiedId(null), 1800);
  };

  const handleDownloadCode = (code: string, lang: string, title?: string) => {
    const extMap: Record<string, string> = {
      typescript: 'ts',
      ts: 'ts',
      tsx: 'tsx',
      javascript: 'js',
      js: 'js',
      jsx: 'jsx',
      python: 'py',
      py: 'py',
      html: 'html',
      css: 'css',
      json: 'json',
      sql: 'sql',
      markdown: 'md',
      md: 'md',
    };
    const ext = extMap[lang.toLowerCase()] || 'txt';
    const blob = new Blob([code], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `${(title || lang || 'snippet').replace(/[^a-zA-Z0-9_-]/g, '_')}.${ext}`;
    link.click();
    URL.revokeObjectURL(url);
  };

  const handleExportTableCSV = (headers: string[], rows: string[][], index: number) => {
    const csvContent = [
      headers.map((h) => `"${h.replace(/"/g, '""')}"`).join(','),
      ...rows.map((row) => row.map((cell) => `"${cell.replace(/"/g, '""')}"`).join(',')),
    ].join('\n');

    const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `table_data_${index + 1}.csv`;
    link.click();
    URL.revokeObjectURL(url);
  };

  if (codeArtifacts.length === 0 && tableArtifacts.length === 0) {
    return (
      <div className="py-12 text-center select-none">
        <Terminal className="w-8 h-8 text-neutral-600 mx-auto mb-2" />
        <p className="text-xs text-neutral-400 font-medium">No code or table artifacts</p>
        <p className="text-[11px] text-neutral-600 mt-1">
          Code blocks and formatted tables generated by AI will appear here
        </p>
      </div>
    );
  }

  return (
    <div className="space-y-4 select-none">
      {/* Code Artifacts */}
      {codeArtifacts.length > 0 && (
        <div>
          <div className="flex items-center gap-1.5 mb-2 text-xs font-semibold text-neutral-400">
            <Code className="w-3.5 h-3.5 text-white" />
            <span>Code Snippets ({codeArtifacts.length})</span>
          </div>
          <div className="space-y-2.5">
            {codeArtifacts.map((art) => (
              <div
                key={art.id}
                className="p-3 bg-[#0B0B0B] border border-[#1C1C1C] rounded-xl space-y-2 shadow-sm"
              >
                <div className="flex items-center justify-between text-xs">
                  <span className="font-mono text-white font-semibold">{art.title || art.language}</span>
                  <div className="flex items-center gap-1.5">
                    <button
                      onClick={() => handleCopy(art.code, art.id)}
                      className="flex items-center gap-1 text-neutral-400 hover:text-white p-1 hover:bg-[#141414] rounded transition-colors"
                      title="Copy snippet"
                    >
                      {copiedId === art.id ? (
                        <Check className="w-3.5 h-3.5 text-emerald-400" />
                      ) : (
                        <Copy className="w-3.5 h-3.5" />
                      )}
                      <span className="text-[10px]">{copiedId === art.id ? 'Copied' : 'Copy'}</span>
                    </button>
                    <button
                      onClick={() => handleDownloadCode(art.code, art.language, art.title)}
                      className="p-1 text-neutral-400 hover:text-white hover:bg-[#141414] rounded transition-colors"
                      title="Download file"
                    >
                      <Download className="w-3.5 h-3.5" />
                    </button>
                  </div>
                </div>
                <pre className="p-2.5 bg-[#050505] rounded-lg text-[11px] font-mono text-neutral-200 overflow-x-auto max-h-36 custom-scrollbar leading-relaxed">
                  <code>{art.code}</code>
                </pre>
              </div>
            ))}
          </div>
        </div>
      )}

      {/* Table Artifacts */}
      {tableArtifacts.length > 0 && (
        <div>
          <div className="flex items-center gap-1.5 mb-2 text-xs font-semibold text-neutral-400">
            <TableIcon className="w-3.5 h-3.5 text-white" />
            <span>Data Tables ({tableArtifacts.length})</span>
          </div>
          <div className="space-y-2.5">
            {tableArtifacts.map((tbl, idx) => (
              <div
                key={idx}
                className="p-2.5 bg-[#0B0B0B] border border-[#1C1C1C] rounded-xl space-y-2 shadow-sm"
              >
                <div className="flex items-center justify-between text-xs px-1">
                  <span className="font-semibold text-white">Table {idx + 1}</span>
                  <button
                    onClick={() => handleExportTableCSV(tbl.headers, tbl.rows, idx)}
                    className="flex items-center gap-1 text-neutral-400 hover:text-white p-1 hover:bg-[#141414] rounded text-[11px] transition-colors"
                    title="Export CSV"
                  >
                    <FileSpreadsheet className="w-3.5 h-3.5 text-emerald-400" />
                    <span>Export CSV</span>
                  </button>
                </div>
                <div className="overflow-x-auto rounded-lg border border-[#1C1C1C] custom-scrollbar">
                  <table className="w-full text-left text-[11px] border-collapse">
                    <thead>
                      <tr className="border-b border-[#1C1C1C] bg-[#050505] text-neutral-200 font-semibold">
                        {tbl.headers.map((h, hIdx) => (
                          <th key={hIdx} className="p-1.5">
                            {h}
                          </th>
                        ))}
                      </tr>
                    </thead>
                    <tbody>
                      {tbl.rows.map((r, rIdx) => (
                        <tr key={rIdx} className="border-b border-[#181818]">
                          {r.map((c, cIdx) => (
                            <td key={cIdx} className="p-1.5 text-neutral-300">
                              {c}
                            </td>
                          ))}
                        </tr>
                      ))}
                    </tbody>
                  </table>
                </div>
              </div>
            ))}
          </div>
        </div>
      )}
    </div>
  );
};
